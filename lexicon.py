def normalize_text(text: str) -> str:
    """Нижний регистр, ё->е, только буквы/цифры, один пробел."""
    text = str(text).lower().replace("ё", "е")
    text = re.sub(r"[^a-zа-я0-9]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def apply_typos(text: str) -> str:
    """Исправить известные опечатки (пословно)."""
    return " ".join(TYPO_MAP.get(word, word) for word in normalize_text(text).split())


def _similar(a: str, b: str) -> float:
    return SequenceMatcher(None, a, b).ratio()


def _phrase_match(text_tokens: list[str], phrase_tokens: list[str],
                  threshold: float = 0.82) -> bool:
    """Фраза совпала с окном текста; длинные слова прощают опечатки."""
    if not phrase_tokens or len(text_tokens) < len(phrase_tokens):
        return False
    for i in range(len(text_tokens) - len(phrase_tokens) + 1):
        window = text_tokens[i:i + len(phrase_tokens)]
        ok = True
        for a, b in zip(window, phrase_tokens):
            if a == b:
                continue
            if len(b) >= 5 and _similar(a, b) >= threshold:
                continue
            ok = False
            break
        if ok:
            return True
    return False


def resolve_category(question: str) -> dict[str, Any] | None:
    """Определить категорию по локальному лексикону.

    Возвращает {"label": str, "types": frozenset[str]} или None.
    Порядок: нормализация опечаток -> словарь синонимов -> type_item.
    """
    tokens = apply_typos(question).split()
    if not tokens:
        return None
    for entry in CATEGORY_SYNONYMS:
        for phrase in entry["synonyms"]:
            if _phrase_match(tokens, normalize_text(phrase).split()):
                return {"label": entry["label"], "types": frozenset(entry["types"])}
    return None