"""Сопоставление вопроса клиента с формулировкой в справочнике инженера.

`unique_answers.parse_source()` уже разбирает `knowledge/unique_answers.md`
в пары «вопрос → ответ» (Task 1). До этого модуля этот разбор читался
только через Claude, а Claude клиенту закрыт (спека §3.2) — «Что такое
УЗДП?» уходило в эскалацию, хотя ответ в справочнике есть. Здесь — прямой
путь без модели: сопоставляем вопрос клиента с вопросом справочника по
словам и, если похоже достаточно, отдаём ответ дословно.

Два рода ошибок сопоставления не равнозначны:

- промах (не нашли то, что есть) — вопрос уйдёт живому человеку. Неприятно,
  но безопасно;
- ложное срабатывание (выдали чужой подтверждённый ответ) — клиент получит
  от лица компании уверенный неверный ответ с меткой «подтверждено
  инженером». Это хуже.

Поэтому весь модуль настроен консервативно: молчание при сомнении, а не
удачный ответ любой ценой (см. `lookup`, `THRESHOLD`).

Fix round 2 (Ruling P): раньше запись сопоставлялась коэффициентом
перекрытия (`|A∩B| / min(|A|,|B|)`) — асимметричной формулой, которая для
короткого вопроса, полностью нашедшегося в записи, всегда даёт 1.0
независимо от того, какую долю записи вопрос покрыл. «Аксессуары к
YCW3?» и «Какая гарантия?» с этой формулой были неотличимы: оба —
короткий вопрос, полностью влезающий в более длинную запись. Round-1
гейт по коду серии залатал только один пример и попутно убил
узнаваемость для ~40 записей с кодом серии в заголовке (клиент почти
никогда не повторяет заголовок дословно — в этом весь смысл модуля).
Round 2 меняет саму метрику: покрытие записи считается взвешенным по
редкости слова внутри справочника (IDF, `_word_weights`), поэтому
непокрытое частое слово («оборудование», «доступны») почти не штрафует,
а непокрытое редкое («YCW3», «корзине») — штрафует сильно. Код-гейта
больше нет.

Fix round 3 (Ruling Q) чинит побочный эффект самого IDF: код серии
("YCW3") встречается примерно в четверти заголовков файла и поэтому
получает НИЗКИЙ вес — статистика видит частое слово, а не то, что это
единственный токен, который называет конкретное изделие. Из-за этого
непокрытый код почти не штрафовал обрывок вроде «дополнительные
аксессуары?». Код изделия — доменный факт, а не частотный: два вопроса,
отличающихся только кодом серии, — разные вопросы, даже если код
встречается в справочнике часто. `_word_weights()` теперь поднимает вес
код-содержащих токенов (`_is_code_token`) до максимума веса в корпусе —
не гейтом (гейт из Round 1 отсекал вопрос целиком и убивал узнаваемость
переформулировок), а именно весом: непокрытый код становится дорогим,
покрытый — приносит максимум пользы записи.
"""
from __future__ import annotations

import math
import re
from dataclasses import dataclass
from functools import lru_cache

import unique_answers
