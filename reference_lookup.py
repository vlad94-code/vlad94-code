# Служебные слова, которые встречаются почти в любом вопросе и сами по
# себе ничего не говорят о теме: вопросительные и указательные местоимения,
# частицы, предлоги, союзы. Не стемминг — просто список форм: без него
# «какая гарантия» и «какая индикация» делили бы слово «какая» как будто
# это сигнал совпадения.
_STOPWORDS = frozenset({
    "какой", "какая", "какое", "какие", "каких", "какому", "каким",
    "какими", "какого", "какою",
    "чей", "чья", "чьё", "чьи", "чьего", "чьему", "чьим", "чьих",
    "что", "чем", "чём", "чего", "чему",
    "это", "этот", "эта", "эти",
    "ли", "же", "бы", "и", "а", "но", "или", "если",
    "у", "в", "во", "на", "с", "со", "к", "ко", "от", "до", "для", "по",
    "при", "из", "о", "об", "за", "над", "под", "про",
    "вы", "вас", "вам", "вами", "мне", "мы", "нас", "нам", "нами",
    "он", "она", "оно", "они", "его", "её", "их", "им", "ими",
    "нужно", "нужен", "нужна", "нужны", "можно",
})

# `_CONTAINMENT_MIN_LEN` и `THRESHOLD` (ниже) тюнились ВМЕСТЕ, прогоном на
# реальном справочнике и на реальном router-регрессионном наборе
# (golden_set.yaml, test_router.py) — это не две независимые ручки.
# `_words_match` определяет, какие пары слов вообще считаются совпадением
# (а значит — что попадает в числитель весов `_score`); `THRESHOLD` — это
# порог по шкале, которую задаёт `_words_match` + `_word_weights`. Смена
# любой из трёх меняет результат для тех же вопросов и требует заново
# прогнать `tests/test_reference_lookup.py` (там же — таблица баллов, на
# которую ориентировались при подборе) и полный набор тестов, а не
# подправить только ту, которая мешает здесь и сейчас.
#
# Минимальная длина слова, начиная с которой одно слово считается
# морфологическим вариантом другого, если является суффиксом другого
# (см. `_words_match`). Ограничение снизу нужно, чтобы короткие слова не
# склеивались по случайному совпадению 2–3 букв (например "ток" не должен
# считаться формой "который").
_CONTAINMENT_MIN_LEN = 4

_WORD_RE = re.compile(r"[a-zа-я0-9]+")
_CODE_TOKEN_RE = re.compile(r"\d")


def _normalize(text: str) -> str:
    return (text or "").lower().replace("ё", "е")


def _meaningful_words(text: str) -> frozenset[str]:
    """Значимые слова вопроса: без регистра, без "ё", без пунктуации,
    без служебных слов из `_STOPWORDS` и без названий городов из
    `managers.CITY_TO_DISTRICT`. Используется и для вопроса клиента, и
    для формулировки справочника — сравнение симметрично.

    Город здесь — параметр вопроса, а не его содержание (Ruling U, fix
    round 2 задачи 7): ответ про способ доставки один и тот же для
    Новосибирска, Хабаровска и Казани, а заголовок записи справочника
    сознательно обобщён и города не называет (Ruling T). Без этого
    исключения название города оставалось бы единственным значимым
    словом вопроса, которое НИЧЕГО не может покрыть, — а с покрытием
    вопроса ниже ~0.52 (см. `_score`) гармоническое среднее не достаёт
    до `THRESHOLD` при любой формулировке записи, и вопрос про доставку
    с названием города тонул бы всегда, только меняя город на новый.
    Выбрасываем город так же, как служебное слово, а не штрафуем за его
    непокрытие.
    """
    words = _WORD_RE.findall(_normalize(text))
    return frozenset(
        w for w in words
        if w not in _STOPWORDS and w not in CITY_TO_DISTRICT and len(w) > 1
    )


def _is_code_token(word: str) -> bool:
    """Слово несёт код изделия — серию или артикул («ycw3», «1p+n»,
    номер артикула): буквы вперемешку с цифрами. Тот же признак, что
    опознавал код-содержащий ВОПРОС целиком в Round 1 (`_is_code_bearing`,
    удалён в Round 2 вместе с гейтом), но здесь это свойство ОДНОГО
    ТОКЕНА для `_word_weights` (Ruling Q, Round 3), а не гейт всего
    сопоставления.
    """
    return bool(_CODE_TOKEN_RE.search(word))


def _words_match(a: str, b: str) -> bool:
    """Одно слово — форма другого: совпадает буквально, либо одно является
    суффиксом другого при длине обоих не меньше `_CONTAINMENT_MIN_LEN`.
    Это не стемминг (ни одно слово не режется по грамматическим правилам)
    — просто допускает разговорные слитные формы вроде «физлицам» напротив
    «физическим лицам»: «лицам» — суффикс «физлицам», и этого достаточно.

    Специально СУФФИКС, а не подстрока где угодно (иначе — вход по
    ЛЮБОЙ общей части): «контакторы» (категория товара) содержит
    «контакт» как ПРЕФИКС и подстроку, но это разные слова с разным
    значением, не падежные формы друг друга. Русские падежные окончания —
    суффиксы, поэтому общий суффикс длиной от `_CONTAINMENT_MIN_LEN` —
    разумный сигнал, а общий префикс/подстрока — нет: однокоренные, но
    самостоятельные слова слишком часто делят префикс.
    """
    if a == b:
        return True
    if len(a) < _CONTAINMENT_MIN_LEN or len(b) < _CONTAINMENT_MIN_LEN:
        return False
    return a.endswith(b) or b.endswith(a)


def _matched_words(question_words: frozenset[str], entry_words: frozenset[str]) -> tuple[frozenset[str], frozenset[str]]:
    """Какие слова вопроса и какие слова записи нашли пару друг в друге
    (через `_words_match`). Общая утилита для `_score` и для тай-брейка
    по precision в `lookup`.
    """
    matched_q = frozenset(qw for qw in question_words if any(_words_match(qw, ew) for ew in entry_words))
    matched_e = frozenset(ew for ew in entry_words if any(_words_match(qw, ew) for qw in question_words))
    return matched_q, matched_e


@lru_cache(maxsize=1)
def _word_weights() -> dict[str, float]:
    """Вес каждого значимого слова, встречающегося в вопросах записей
    справочника.

    База — IDF: слово, которое есть только в одной записи («гарантия»,
    «уздп»), весит много; слово, которое есть во многих записях
    («оборудование», «доступны», «как»), весит мало. Файл маленький
    (десятки записей) и правится редко — вес считается один раз при
    разборе и кэшируется вместе с `entries()` (`clear_cache()`
    сбрасывает оба). Формула — сглаженный IDF (`log((N+1)/(df+1)) + 1`):
    даёт положительный вес даже слову, встретившемуся во всех записях
    сразу, и растёт для более редких слов без разрыва при df=0.

    Исключение (Ruling Q, Round 3): код изделия («YCW3», «1P+N») —
    доменный факт, а не частотный. Он встречается почти в трети
    заголовков файла (одно на несколько десятков моделей серии YCW3/
    YCM3/...) и поэтому получает НИЗКИЙ IDF — но именно он называет
    конкретное изделие, а не общая частота его упоминания в справочнике.
    Два вопроса, отличающихся только кодом серии, — разные вопросы, даже
    если код встречается часто. Такие токены (`_is_code_token`)
    поднимаются до максимального веса в корпусе — не отдельным
    множителем и не гейтом (гейт отсекал бы вопрос целиком, здесь только
    поднимается цена его отсутствия), а именно потолком: код изделия не
    может весить МЕНЬШЕ, чем самое редкое обычное слово справочника.
    """
    document_frequency: dict[str, int] = {}
    for entry in entries():
        for word in _meaningful_words(entry.question):
            document_frequency[word] = document_frequency.get(word, 0) + 1
    total = len(entries())
    weights = {
        word: math.log((total + 1) / (df + 1)) + 1
        for word, df in document_frequency.items()
    }
    if weights:
        max_weight = max(weights.values())
        for word in weights:
            if _is_code_token(word):
                weights[word] = max_weight
    return weights


def _weighted_coverage(matched: frozenset[str], words: frozenset[str], weights: dict[str, float]) -> float:
    """Доля ВЕСА слов `words`, приходящаяся на совпавшие `matched` — не
    доля их КОЛИЧЕСТВА. Непокрытое частое слово («оборудование») почти не
    снижает эту долю, непокрытое редкое («YCW3», «корзине») — снижает
    сильно. Используется только для стороны ЗАПИСИ (см. `_score`) —
    сторона вопроса весами не взвешивается по требованию Ruling P.
    """
    if not words:
        return 0.0
    total_weight = sum(weights.get(w, 0.0) for w in words)
    if total_weight <= 0:
        return 0.0
    return sum(weights.get(w, 0.0) for w in matched) / total_weight


def _score(matched_q: frozenset[str], matched_e: frozenset[str], question_words: frozenset[str], entry_words: frozenset[str], weights: dict[str, float]) -> float:
    """Гармоническое среднее двух покрытий (Ruling P):

    - `entry_coverage` — взвешенная по IDF доля записи, объяснённая
      вопросом (`_weighted_coverage`). Ловит случай, когда вопрос —
      только обрывок длинной записи, но подобрал единственное редкое
      слово, которое отличает её от всех остальных («YCW3», «уздп»).
    - `question_coverage` — обычная (не взвешенная) доля значимых слов
      ВОПРОСА, нашедшихся в записи. Ловит обратный случай: вопрос
      спросил больше, чем есть в этой записи.

    Гармоническое среднее, а не среднее арифметическое или минимум:
    оно требует, чтобы ОБЕ доли были одновременно приличными — если хотя
    бы одна близка к нулю, итоговый балл тоже близок к нулю (в отличие от
    среднего арифметического, которое одна высокая доля может вытащить
    в одиночку). Раньше (Round 1) использовался коэффициент перекрытия
    `|A∩B| / min(|A|,|B|)` — он структурно давал 1.0 любому короткому
    вопросу, полностью нашедшемуся в записи, вне зависимости от того,
    какую долю записи он покрыл («аксессуары к YCW3» получал ту же
    оценку, что и «Какая гарантия?»). `question_coverage` здесь — это,
    по сути, полный recall вопроса (числитель совпадает со знаменателем
    только когда весь вопрос объяснён), а `entry_coverage` добавляет
    вторую, недостающую половину: насколько сильно за пределами вопроса
    осталось СОДЕРЖАНИЕ записи, взвешенное по редкости слов.
    """
    if not matched_q or not question_words:
        return 0.0
    entry_coverage = _weighted_coverage(matched_e, entry_words, weights)
    question_coverage = len(matched_q) / len(question_words)
    if entry_coverage <= 0 or question_coverage <= 0:
        return 0.0
    return 2 * entry_coverage * question_coverage / (entry_coverage + question_coverage)


# Порог отсечки. Пересчитан заново после Ruling Q (Fix round 3, полная
# таблица — в fix-отчёте задачи 6a) — прежнее значение 0.62 подбиралось
# под другую весовую схему (без потолка веса для кода изделия) и здесь
# не годится.
#
# Ruling Q поднял вес код-содержащих токенов («YCW3», «YCM3», ...) до
# максимума в корпусе. Эффект в обе стороны, как и предсказывалось:
# - «дополнительные аксессуары?» (не содержит кода в тексте вопроса)
#   ПОТЕРЯЛА балл: 0.7143 → 0.6561 — теперь дешёвого «YCW3» в записи
#   больше нет, непокрытый код стал дорогим, и старый конфликт с
#   «Какая гарантия?» (0.6879) исчез сам собой — 0.6561 < 0.6879;
# - «аксессуары к YCW3» (содержит код) НАБРАЛА балл: 0.6153 → 0.6771 —
#   покрыла дорогой код, и это ТЕПЕРЬ самый высокий балл среди всех, кто
#   обязан молчать (MUST_SILENT), и он вплотную подошёл к минимуму
#   ANSWERABLE (0.6879).
#
# Полный перебор порога (скрипт в отчёте) показал: окно, где ANSWERABLE
# 6/6 и MUST_SILENT 12/12 одновременно, — (0.6771, 0.6879]. THRESHOLD=0.68
# взят внутри него. НО в этом узком окне RECALL14 даёт только 9 из 14
# (нужно ≥10) — ещё два вопроса («Какая категория применения у YCW3?»,
# 0.6667; «Какую выбрать: YCM1, YCM8 или YCM3?», 0.6709) не дотягивают:
# их заголовки в справочнике объединяют по два разных факта в одном
# вопросе, и обрывок, спрашивающий только про один из них, законно не
# покрывает вторую половину записи.
#
# Понижение THRESHOLD ниже 0.6771 вернуло бы недостающие пункты recall,
# но тогда «аксессуары к YCW3» перестало бы молчать — а MUST_SILENT
# «все двенадцать позиций» не допускает исключений (в отличие от
# RECALL14, где до четырёх промахов разрешено). Выбор в пользу молчания,
# а не ответа: ложное срабатывание хуже промаха (см. модуль-докстринг).
# Второй неразрешимый конфликт после Round 2 — статус DONE_WITH_CONCERNS,
# решение по нему за контроллером (Fix round 3, отчёт).
THRESHOLD = 0.68


@dataclass(frozen=True)
class Match:
    question: str
    answer: str
    category: str
    score: float


@lru_cache(maxsize=1)
def entries() -> tuple:
    """Записи справочника, разобранные один раз и закэшированные — как
    `catalog_search.products()`. Файл небольшой и правится редко (правка
    требует отдельного `python unique_answers.py`), пересобирать разбор
    на каждый вопрос незачем.
    """
    text = unique_answers.SOURCE_PATH.read_text(encoding="utf-8")
    return tuple(unique_answers.parse_source(text))


def clear_cache() -> None:
    """Сбросить кэш разбора и весов слов — для тестов, которые подменяют
    файл справочника (см. `catalog_search.clear_cache`). Веса (`_word_weights`)
    считаются из `entries()`, поэтому сбрасываются вместе с ним — иначе
    тест с подменённым справочником продолжил бы использовать частоты
    слов из предыдущего (настоящего или другого поддельного) файла."""
    entries.cache_clear()
    _word_weights.cache_clear()


def lookup(question: str, threshold: float = THRESHOLD) -> Match | None:
    """Найти запись справочника, отвечающую на вопрос клиента.

    Возвращает лучшее совпадение, только если его оценка не ниже порога.
    Молчание (None) лучше неверного подтверждённого ответа — вопрос без
    уверенного совпадения должен уйти в эскалацию к человеку, а не быть
    закрыт похожим, но не тем ответом.

    Тай-брейк (Fix round 1, находка 2, Ruling N): если несколько записей
    набрали одинаковый максимальный балл, но отвечают на разное — это
    сигнал, что вопрос недоспецифицирован относительно гранулярности
    справочника, а не повод отдать клиенту одну из них под меткой
    «подтверждено инженером» только потому, что она раньше по файлу.
    Побеждает запись, которую вопрос покрывает ПОЛНЕЕ (выше `precision`
    — доля СЛОВ, а не взвешенная: тай-брейк оставлен как в Round 1, он
    решает другую задачу — не порог, а выбор между уже прошедшими); если
    и это не разводит записи, а ответы у них по существу разные —
    возвращается None.
    """
    question_words = _meaningful_words(question)
    if not question_words:
        return None
    weights = _word_weights()

    # (score, precision, entry) для каждой прошедшей записи. precision —
    # доля слов ЗАПИСИ, объяснённая вопросом (matched_e / |entry_words|,
    # без весов): тай-брейк ниже предпочитает запись, в которой у вопроса
    # меньше всего осталось "лишнего" необъяснённого содержания, то есть
    # запись — самый узкий/точный из равновероятных ответов.
    candidates: list[tuple[float, float, object]] = []
    for entry in entries():
        entry_words = _meaningful_words(entry.question)
        if not entry_words:
            continue
        matched_q, matched_e = _matched_words(question_words, entry_words)
        if not matched_q:
            continue
        score = _score(matched_q, matched_e, question_words, entry_words, weights)
        if score < threshold:
            continue
        precision = len(matched_e) / len(entry_words)
        candidates.append((score, precision, entry))

    if not candidates:
        return None

    best_score = max(c[0] for c in candidates)
    top = [c for c in candidates if c[0] == best_score]
    if len(top) > 1:
        best_precision = max(c[1] for c in top)
        top = [c for c in top if c[1] == best_precision]
    if len(top) > 1 and len({c[2].answer for c in top}) > 1:
        # Ничья на равном счёте и равной точности между записями с
        # разными ответами — сигнал, что вопрос недоспецифицирован
        # относительно гранулярности справочника (Ruling N), а не повод
        # выбрать произвольную запись под меткой «подтверждено инженером».
        return None

    score, _, entry = top[0]
    return Match(question=entry.question, answer=entry.answer, category=entry.category, score=score)


def lookup_combined(question: str, threshold: float = THRESHOLD) -> Match | None:
    """Словарный поиск, затем — смысловой как второй шанс.

    Порядок именно такой:

    1. `lookup()` — совпадение по словам. Оно точное и годами оттюнинговано
       под этот справочник (см. THRESHOLD и его историю), поэтому если оно
       нашло запись — доверяем ей и дальше не идём. Так весь набор тестов
       словарного поиска (`tests/test_reference_lookup.py`) остаётся в силе:
       поведение для вопросов, которые он и так покрывал, не меняется.

    2. `semantic_reference.best_match()` — поиск по СМЫСЛУ. Он подключается
       ровно там, где словарный промолчал: у вопроса нет общих значимых слов
       с записью, но есть общий смысл («во сколько обойдётся» ↔ «стоимость»).
       Если модель эмбеддингов недоступна (не установлена библиотека, нет
       скачанной модели, CI без сети) — `best_match()` вернёт None, и мы
       просто останемся с результатом словарного поиска. Ничего не ломается.

    Оба прохода одинаково консервативны: при сомнении — None, вопрос уйдёт
    живому человеку. Ложный ответ с меткой «подтверждено инженером» хуже
    промаха (см. докстринг модуля).
    """
    match = lookup(question, threshold)
    if match is not None:
        return match

    # Локальный импорт: тяжёлую библиотеку эмбеддингов не тянем, пока она
    # реально не понадобилась, и избегаем кольца импортов с semantic_reference
    # (тот импортирует reference_lookup внутри своих функций).
    import semantic_reference

    semantic = semantic_reference.best_match(question)
    if semantic is None:
        return None
    return Match(
        question=semantic.question,
        answer=semantic.answer,
        category=semantic.category,
        score=semantic.score,
    )
